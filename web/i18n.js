  function normalizeUiLang(code) {
    const lang = String(code || "en").trim().toLowerCase();
    return UI_LANGS.includes(lang) ? lang : "en";
  }

  function loadUiLanguage() {
    try {
      return normalizeUiLang(localStorage.getItem(UI_LANG_STORAGE_KEY));
    } catch {
      return "en";
    }
  }

  function saveUiLanguage(code) {
    const lang = normalizeUiLang(code);
    try {
      localStorage.setItem(UI_LANG_STORAGE_KEY, lang);
    } catch {
      /* ignore quota */
    }
    return lang;
  }

  let currentLang = loadUiLanguage();

  function uiLanguage() {
    return currentLang;
  }

  function t(key, vars = null) {
    const table = STRINGS[currentLang] || STRINGS.en;
    let text = table[key] ?? STRINGS.en[key] ?? key;
    if (vars && typeof vars === "object") {
      text = text.replace(/\{(\w+)\}/g, (_, name) => (
        Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`
      ));
    }
    return text;
  }

  function applyStaticI18n(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((node) => {
      const key = node.getAttribute("data-i18n");
      if (!key) return;
      node.textContent = t(key);
    });
    root.querySelectorAll("[data-i18n-html]").forEach((node) => {
      const key = node.getAttribute("data-i18n-html");
      if (!key) return;
      node.innerHTML = t(key);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      const key = node.getAttribute("data-i18n-placeholder");
      if (!key) return;
      node.setAttribute("placeholder", t(key));
    });
    root.querySelectorAll("[data-i18n-title]").forEach((node) => {
      const key = node.getAttribute("data-i18n-title");
      if (!key) return;
      node.setAttribute("title", t(key));
    });
    root.querySelectorAll("[data-i18n-aria]").forEach((node) => {
      const key = node.getAttribute("data-i18n-aria");
      if (!key) return;
      node.setAttribute("aria-label", t(key));
    });
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute("content", t("meta.description"));
    document.documentElement.lang = currentLang;
  }

  function setUiLanguage(code, { persist = true } = {}) {
    currentLang = persist ? saveUiLanguage(code) : normalizeUiLang(code);
    applyStaticI18n();
    return currentLang;
  }

